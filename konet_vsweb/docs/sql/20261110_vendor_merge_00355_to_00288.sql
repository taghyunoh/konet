-- ① 확인 — 00355 가 남은 건수 (기대 : 27 · 68 · 71)
SELECT 'TBL_SALES_TRX_MST'      AS 표, COUNT(*) AS 건수 FROM TBL_SALES_TRX_MST      WHERE CUST_CD   = '00355'
UNION ALL
SELECT 'TBL_STOCK_LEDGER',             COUNT(*)          FROM TBL_STOCK_LEDGER       WHERE VENDOR_CD = '00355'
UNION ALL
SELECT 'TBL_PROD_SALEPRICE_HST',       COUNT(*)          FROM TBL_PROD_SALEPRICE_HST WHERE VENDOR_CD = '00355';

SELECT VENDOR_CD, VENDOR_NM, BIZNO, ACTION_YN FROM TBL_VENDOR_MST WHERE VENDOR_CD IN ('00355', '00288');

-- ② 백업 (이미 있으면 건너뛴다)
IF OBJECT_ID('dbo.BAK_20261110_V355_SALES', 'U') IS NULL
  SELECT SALE_SEQ, CUST_CD, CUST_NM, UPD_DTTM, UPD_USER INTO dbo.BAK_20261110_V355_SALES
    FROM TBL_SALES_TRX_MST WHERE CUST_CD = '00355';
IF OBJECT_ID('dbo.BAK_20261110_V355_LEDGER', 'U') IS NULL
  SELECT LEDGER_SEQ, VENDOR_CD, VENDOR_NM, UPD_DTTM, UPD_USER INTO dbo.BAK_20261110_V355_LEDGER
    FROM TBL_STOCK_LEDGER WHERE VENDOR_CD = '00355';
IF OBJECT_ID('dbo.BAK_20261110_V355_SALEPRICE', 'U') IS NULL
  SELECT SALEPRICE_SEQ, VENDOR_CD, VENDOR_NM, UPD_DTTM, UPD_USER INTO dbo.BAK_20261110_V355_SALEPRICE
    FROM TBL_PROD_SALEPRICE_HST WHERE VENDOR_CD = '00355';
IF OBJECT_ID('dbo.BAK_20261110_V355_VENDOR', 'U') IS NULL
  SELECT * INTO dbo.BAK_20261110_V355_VENDOR FROM TBL_VENDOR_MST WHERE VENDOR_CD = '00355';

-- ③ 고치기 — 한 묶음으로
BEGIN TRAN;

DECLARE @nm NVARCHAR(200) = (SELECT TOP 1 VENDOR_NM FROM TBL_VENDOR_MST WHERE VENDOR_CD = '00288' AND ACTION_YN = 'Y');
DECLARE @now VARCHAR(19) = CONVERT(VARCHAR(19), GETDATE(), 120);

UPDATE TBL_SALES_TRX_MST
   SET CUST_CD = '00288', CUST_NM = ISNULL(@nm, CUST_NM), UPD_DTTM = @now, UPD_USER = 'merge20261110'
 WHERE CUST_CD = '00355';
-- 기대 : 27

UPDATE TBL_STOCK_LEDGER
   SET VENDOR_CD = '00288', VENDOR_NM = ISNULL(@nm, VENDOR_NM), UPD_DTTM = @now, UPD_USER = 'merge20261110'
 WHERE VENDOR_CD = '00355';
-- 기대 : 68

UPDATE TBL_PROD_SALEPRICE_HST
   SET VENDOR_CD = '00288', VENDOR_NM = ISNULL(@nm, VENDOR_NM), UPD_DTTM = @now, UPD_USER = 'merge20261110'
 WHERE VENDOR_CD = '00355';
-- 기대 : 71

UPDATE TBL_VENDOR_MST
   SET ACTION_YN = 'N', UPD_DTTM = @now, UPD_USER = 'merge20261110'
 WHERE VENDOR_CD = '00355' AND ACTION_YN = 'Y';
-- 기대 : 1

-- 네 UPDATE 가 기대 건수대로면 COMMIT, 아니면 ROLLBACK
COMMIT;
-- ROLLBACK;

-- ④ 확인 — 00355 가 남은 곳 0건, 00288 건수
