/* 현재고 다시 세기 — 앱 recalcStockMst 와 같은 식(세 상품 모두 TBL_STOCK_MST 행이 이미 있다) */
UPDATE t
   SET t.CUR_QTY        = ISNULL(s.CUR_QTY, 0),
       t.AVG_IN_PRICE   = CASE WHEN ISNULL(s.IN_QTY, 0) = 0 THEN t.AVG_IN_PRICE ELSE s.IN_AMT / s.IN_QTY END,
       t.LAST_INPRICE   = ISNULL((SELECT TOP 1 UNIT_PRICE FROM TBL_STOCK_LEDGER l WHERE l.PROD_SEQ = t.PROD_SEQ AND l.ACTION_YN = 'Y' AND l.IO_GB = 'I' AND l.COMP_CD = t.COMP_CD ORDER BY l.TRX_DT DESC, l.LEDGER_SEQ DESC), t.LAST_INPRICE),
       t.LAST_SALEPRICE = ISNULL((SELECT TOP 1 UNIT_PRICE FROM TBL_STOCK_LEDGER l WHERE l.PROD_SEQ = t.PROD_SEQ AND l.ACTION_YN = 'Y' AND l.IO_GB = 'O' AND l.COMP_CD = t.COMP_CD ORDER BY l.TRX_DT DESC, l.LEDGER_SEQ DESC), t.LAST_SALEPRICE),
       t.STOCK_AMT      = ISNULL(s.CUR_QTY, 0) * CASE WHEN ISNULL(s.IN_QTY, 0) = 0 THEN ISNULL(t.AVG_IN_PRICE, 0) ELSE s.IN_AMT / s.IN_QTY END,
       t.LAST_IN_DT     = s.LAST_IN_DT,
       t.LAST_OUT_DT    = s.LAST_OUT_DT,
       t.UPD_DTTM       = CONVERT(VARCHAR(19), GETDATE(), 120), t.UPD_USER = 'fix20261116'
  FROM TBL_STOCK_MST t
 CROSS APPLY (
        SELECT SUM(CASE WHEN l.IO_GB IN ('I','R') THEN l.QTY WHEN l.IO_GB = 'O' THEN -l.QTY WHEN l.IO_GB = 'A' THEN l.QTY ELSE 0 END) AS CUR_QTY,
               SUM(CASE WHEN l.IO_GB = 'I' THEN l.QTY * ISNULL(l.UNIT_PRICE, 0) ELSE 0 END) AS IN_AMT,
               SUM(CASE WHEN l.IO_GB = 'I' AND (ISNULL(l.UNIT_PRICE, 0) <> 0 OR z.ZY = 'Y') THEN l.QTY ELSE 0 END) AS IN_QTY,
               MAX(CASE WHEN l.IO_GB = 'I' THEN l.TRX_DT END) AS LAST_IN_DT,
               MAX(CASE WHEN l.IO_GB = 'O' THEN l.TRX_DT END) AS LAST_OUT_DT
          FROM TBL_STOCK_LEDGER l
         CROSS JOIN (SELECT ISNULL((SELECT TOP 1 AVG_ZERO_YN FROM TBL_COMP_SET WHERE COMP_CD = 'W1234567'), 'Y') AS ZY) z
         WHERE l.PROD_SEQ = t.PROD_SEQ AND l.ACTION_YN = 'Y' AND l.COMP_CD = t.COMP_CD ) s
 WHERE t.COMP_CD = 'W1234567' AND t.PROD_SEQ IN (936, 937, 1430);
